"""Regenerate the Go symbol tables from the installed upstream Python package."""
import json
from pathlib import Path
from telegramify_markdown.latex_escape import const

quote = lambda s: json.dumps(s, ensure_ascii=False)
lines = ['// Code generated by scripts/generate_latex.py; DO NOT EDIT.', 'package telegramify', '']
for name, value in [('latexSymbols', const.LATEX_SYMBOLS), ('notMap', const.NOT_MAP), ('subscripts', const.SUBSCRIPTS), ('superscripts', const.SUPERSCRIPTS), ('fractions', {a+'/'+b:v for (a,b),v in const.FRAC_MAP.items()})]:
    lines.append(f'var {name} = map[string]string{{')
    lines.extend(f'{quote(k)}: {quote(v)},' for k,v in sorted(value.items()))
    lines.append('}')
lines.append('var latexStyles = map[string]map[string]string{')
for k, v in sorted(const.LATEX_STYLES.items()):
    lines.append(quote(k)+': {')
    lines.extend(f'{quote(a)}: {quote(b)},' for a,b in sorted(v.items()))
    lines.append('},')
lines.append('}')
lines.append('var combining = map[string]struct { mark string; position string }{')
for k, (v, typ) in sorted(const.COMBINING.items()):
    lines.append(f'{quote(k)}: {{{quote(v)}, {quote(next(name for name in ('FirstChar', 'LastChar', 'EveryChar') if getattr(const.CombiningType, name) == typ))}}},')
lines.append('}')
Path(__file__).resolve().parents[1].joinpath('latex_tables.go').write_text('\n'.join(lines)+'\n')
